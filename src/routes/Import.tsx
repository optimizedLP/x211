import { useMemo, useState } from 'react'
import { Link } from 'react-router-dom'

import { DELIMITER_LABELS, buildTable } from '../lib/csv'
import type { ParsedTable } from '../lib/csv'
import { inventory } from '../lib/data'
import type { ImportOutcome } from '../lib/data'
import {
  IMPORT_FIELDS,
  UNMAPPED,
  buildImportPlan,
  columnSample,
  emptyMapping,
  suggestMapping,
} from '../lib/importPlan'
import type { ImportMapping } from '../lib/importPlan'
import { useAsync } from '../lib/useAsync'
import { useInventoryVersion } from '../lib/useInventoryVersion'

const PREVIEW_LIMIT = 30

const SELECT_CLASS =
  'mt-1 w-full rounded-lg border border-line bg-panel-2 px-2.5 py-1.5 text-xs text-ink focus:border-accent/60 focus:ring-2 focus:ring-accent/20 focus:outline-none'

const TEMPLATE_HEADERS = [
  'Asset tag',
  'Serial',
  'Category',
  'Brand',
  'Location',
  'Holder',
  'Status',
  'Warranty end',
  'Notes',
  'Model',
]

function downloadTemplate(): void {
  const csv = `${TEMPLATE_HEADERS.join(',')}\nX211-1050,SAMPLE0001,Chromebook,Acer,Room 214,,In Service,2027-08-30,,Chromebook 314 C736\n`
  const url = URL.createObjectURL(new Blob([csv], { type: 'text/csv;charset=utf-8' }))
  const link = document.createElement('a')
  link.href = url
  link.download = 'x211-device-import-template.csv'
  link.click()
  URL.revokeObjectURL(url)
}

/**
 * Spreadsheet import, in one screen: drop the sheet, confirm the column
 * mapping, read the dry run, then write.
 *
 * The preview is generated by the same function that produces the records, so
 * what is shown is exactly what would be written — there is no second, more
 * permissive path at commit time.
 */
export function ImportPage() {
  const version = useInventoryVersion()

  const categoriesState = useAsync(() => inventory.listCategories(), [])
  const locationsState = useAsync(() => inventory.listLocations(), [])
  const staffState = useAsync(() => inventory.listStaff(), [])
  // Retired and removed units included: their asset tags are still taken, so a
  // restored record can never collide with one imported in the meantime.
  const existingState = useAsync(
    () => inventory.listDevices({ includeRetired: true, includeDeleted: true }),
    [version],
  )

  const categories = useMemo(() => categoriesState.data ?? [], [categoriesState.data])
  const locations = useMemo(() => locationsState.data ?? [], [locationsState.data])
  const staff = useMemo(() => staffState.data ?? [], [staffState.data])
  const existing = useMemo(() => existingState.data ?? [], [existingState.data])

  const [rawText, setRawText] = useState('')
  const [hasHeaderRow, setHasHeaderRow] = useState(true)
  const [table, setTable] = useState<ParsedTable | null>(null)
  const [mapping, setMapping] = useState<ImportMapping>(emptyMapping)
  const [fallbackCategoryId, setFallbackCategoryId] = useState('')
  const [sourceName, setSourceName] = useState('')
  const [pasted, setPasted] = useState('')
  const [loadError, setLoadError] = useState<string | null>(null)
  const [commitError, setCommitError] = useState<string | null>(null)
  const [committing, setCommitting] = useState(false)
  const [result, setResult] = useState<{
    outcome: ImportOutcome
    skippedRows: { rowNumber: number; tag: string }[]
  } | null>(null)
  const [fileKey, setFileKey] = useState(0)

  const referencesLoading =
    categoriesState.loading || locationsState.loading || staffState.loading || existingState.loading

  const plan = useMemo(() => {
    if (!table) return null
    return buildImportPlan({
      table,
      mapping,
      fallbackCategoryId,
      categories,
      locations,
      staff,
      existing,
    })
  }, [table, mapping, fallbackCategoryId, categories, locations, staff, existing])

  const applyText = (text: string, name: string) => {
    const parsed = buildTable(text, hasHeaderRow)
    if (parsed.headers.length === 0 || parsed.rows.length === 0) {
      setLoadError(
        'No rows found in that file. Check it is a CSV export and not the original .xlsx — Excel’s “Save As → CSV UTF-8” does the conversion.',
      )
      return
    }
    setRawText(text)
    setTable(parsed)
    setMapping(suggestMapping(parsed.headers))
    setSourceName(name)
    setLoadError(null)
    setCommitError(null)
    setResult(null)
  }

  const readFile = async (file: File) => {
    try {
      applyText(await file.text(), file.name)
    } catch (error) {
      setLoadError(error instanceof Error ? error.message : String(error))
    }
  }

  const changeHeaderRow = (value: boolean) => {
    setHasHeaderRow(value)
    if (!rawText) return
    const next = buildTable(rawText, value)
    if (next.headers.length === 0) return
    setTable(next)
    setMapping(suggestMapping(next.headers))
  }

  const reset = () => {
    setRawText('')
    setTable(null)
    setMapping(emptyMapping())
    setFallbackCategoryId('')
    setSourceName('')
    setPasted('')
    setLoadError(null)
    setCommitError(null)
    setResult(null)
    setFileKey((previous) => previous + 1)
  }

  const commit = async () => {
    if (!plan || committing || plan.ready === 0) return
    const ready = plan.rows.filter((row) => row.errors.length === 0 && row.input)
    const inputs = ready.flatMap((row) => (row.input ? [row.input] : []))
    setCommitting(true)
    setCommitError(null)
    try {
      const outcome = await inventory.importDevices(inputs)
      // The adapter dedupes against what is on disk, so it can still refuse a
      // row the preview accepted. Map those tags back to their source rows.
      const skippedRows = ready.flatMap((row) => {
        const tag = row.preview.assetTag.toUpperCase()
        return outcome.duplicates.some((duplicate) => duplicate.toUpperCase() === tag)
          ? [{ rowNumber: row.rowNumber, tag: row.preview.assetTag }]
          : []
      })
      setResult({ outcome, skippedRows })
    } catch (error) {
      setCommitError(error instanceof Error ? error.message : String(error))
    } finally {
      setCommitting(false)
    }
  }

  // --- result -----------------------------------------------------------------

  if (result) {
    const { created, duplicates } = result.outcome
    return (
      <div className="max-w-2xl space-y-5">
        <div>
          <Link to="/" className="text-xs text-muted transition-colors hover:text-accent">
            ← Devices
          </Link>
          <h1 className="mt-2 text-2xl font-semibold tracking-tight">Import finished</h1>
        </div>

        <div className="rounded-xl border border-accent-2/40 bg-accent-2/10 p-5">
          <p className="text-sm text-ink">
            <strong>{created.length}</strong> {created.length === 1 ? 'device' : 'devices'} added from{' '}
            {sourceName || 'the pasted sheet'}.
          </p>
          <p className="mt-1 text-xs text-muted">
            They are in the fleet now — the sidebar counts and the warranty cliff already include them.
          </p>
        </div>

        {duplicates.length > 0 && (
          <div className="rounded-xl border border-warn/40 bg-warn/10 p-5 text-sm">
            <p className="font-semibold text-warn">
              {duplicates.length} {duplicates.length === 1 ? 'row was' : 'rows were'} skipped
            </p>
            <p className="mt-1 text-xs text-muted">
              Those asset tags already existed. Nothing was overwritten — edit the existing record instead.
            </p>
            <ul className="mt-2 space-y-0.5 font-mono text-[11px] text-warn">
              {result.skippedRows.map((row) => (
                <li key={`${row.rowNumber}-${row.tag}`}>
                  row {row.rowNumber}: {row.tag}
                </li>
              ))}
            </ul>
          </div>
        )}

        <div className="flex flex-wrap gap-2">
          <Link
            to="/"
            className="rounded-lg border border-accent/50 bg-accent/15 px-3 py-1.5 text-xs font-semibold text-accent transition-colors hover:bg-accent/25"
          >
            View the fleet
          </Link>
          <button
            type="button"
            onClick={reset}
            className="rounded-lg border border-line px-3 py-1.5 text-xs font-semibold text-muted transition-colors hover:text-ink"
          >
            Import another file
          </button>
        </div>
      </div>
    )
  }

  // --- upload -----------------------------------------------------------------

  if (!table) {
    return (
      <div className="max-w-2xl space-y-5">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight">Import from Excel</h1>
          <p className="mt-1 text-sm text-muted">
            Upload your existing inventory sheet, check the column mapping, then look at the dry run.
            Nothing is written until you press import.
          </p>
        </div>

        <div className="space-y-5 rounded-xl border border-line bg-panel p-5">
          <div>
            <label className="block">
              <span className="text-xs font-semibold text-ink">CSV file</span>
              <input
                key={fileKey}
                type="file"
                accept=".csv,.tsv,.txt,text/csv,text/plain"
                onChange={(event) => {
                  const file = event.target.files?.[0]
                  if (file) void readFile(file)
                }}
                className="mt-2 block w-full cursor-pointer rounded-lg border border-line bg-panel-2 px-3 py-2 text-xs text-muted file:mr-3 file:rounded-md file:border-0 file:bg-accent/15 file:px-3 file:py-1.5 file:text-xs file:font-semibold file:text-accent"
              />
            </label>
            <p className="mt-2 text-[11px] leading-relaxed text-muted">
              Excel file? Use <strong className="text-ink">File → Save As → CSV UTF-8</strong> and upload
              that. Comma, semicolon and tab separated all work — the separator is detected.
            </p>
          </div>

          <div className="border-t border-line/60 pt-4">
            <label className="block">
              <span className="text-xs font-semibold text-ink">…or paste the rows</span>
              <textarea
                value={pasted}
                onChange={(event) => setPasted(event.target.value)}
                rows={4}
                placeholder="Select cells in Excel, copy, and paste here — tabs come through as columns."
                className="mt-2 w-full resize-y rounded-lg border border-line bg-panel-2 px-3 py-2 font-mono text-xs text-ink placeholder:font-sans placeholder:text-muted/60 focus:border-accent/60 focus:ring-2 focus:ring-accent/20 focus:outline-none"
              />
            </label>
            <button
              type="button"
              disabled={pasted.trim() === ''}
              onClick={() => applyText(pasted, 'pasted rows')}
              className="mt-2 rounded-lg border border-accent/50 bg-accent/15 px-3 py-1.5 text-xs font-semibold text-accent transition-colors hover:bg-accent/25 disabled:opacity-40"
            >
              Use pasted rows
            </button>
          </div>

          <label className="flex items-center gap-2 text-xs text-muted">
            <input
              type="checkbox"
              checked={hasHeaderRow}
              onChange={(event) => setHasHeaderRow(event.target.checked)}
              className="size-3.5 accent-[#5b8cff]"
            />
            The first row is a header row
          </label>

          {loadError && (
            <p className="rounded-lg border border-bad/40 bg-bad/10 px-3 py-2 text-xs text-bad">{loadError}</p>
          )}
        </div>

        <div className="rounded-xl border border-line bg-panel p-5 text-xs text-muted">
          <p className="font-semibold text-ink">No sheet yet?</p>
          <p className="mt-1 leading-relaxed">
            Download a blank template, fill it in, and re-upload — the columns already match, so the
            mapping step will fill itself in.
          </p>
          <button
            type="button"
            onClick={downloadTemplate}
            className="mt-3 rounded-lg border border-line px-3 py-1.5 text-xs font-semibold text-muted transition-colors hover:border-accent/40 hover:text-accent"
          >
            Download CSV template
          </button>
        </div>
      </div>
    )
  }

  // --- mapping + dry run ------------------------------------------------------

  const previewRows = plan?.rows.slice(0, PREVIEW_LIMIT) ?? []
  const categoriesForFallback = categories.filter((category) => category.trackingType === 'serialized')

  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight">Import from Excel</h1>
          <p className="mt-1 text-sm text-muted">
            {sourceName} · {table.rows.length} data {table.rows.length === 1 ? 'row' : 'rows'} ·{' '}
            {DELIMITER_LABELS[table.delimiter]}-separated
            {table.hasHeaderRow ? '' : ' · no header row'}
          </p>
        </div>
        <div className="flex flex-wrap items-center gap-4">
          <label className="flex items-center gap-2 text-xs text-muted">
            <input
              type="checkbox"
              checked={hasHeaderRow}
              onChange={(event) => changeHeaderRow(event.target.checked)}
              className="size-3.5 accent-[#5b8cff]"
            />
            First row is a header
          </label>
          <button
            type="button"
            onClick={reset}
            className="rounded-lg border border-line px-3 py-1.5 text-xs font-semibold text-muted transition-colors hover:text-ink"
          >
            Start over
          </button>
        </div>
      </div>

      <section className="space-y-4 rounded-xl border border-line bg-panel p-5">
        <div className="flex flex-wrap items-baseline justify-between gap-2">
          <h2 className="text-xs font-bold tracking-wider text-muted uppercase">Column mapping</h2>
          <span className="text-[11px] text-muted">
            Guessed from the header names — change anything that looks wrong.
          </span>
        </div>

        <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
          {IMPORT_FIELDS.map((field) => {
            const column = mapping[field.key]
            const sample = column === UNMAPPED ? null : columnSample(table, column)
            return (
              <label key={field.key} className="block">
                <span className="text-xs text-muted">
                  {field.label}
                  {field.required && !(field.key === 'category' && fallbackCategoryId) && (
                    <span className="ml-1.5 font-semibold text-bad">required</span>
                  )}
                </span>
                <select
                  value={column}
                  onChange={(event) =>
                    setMapping((previous) => ({
                      ...previous,
                      [field.key]: Number(event.target.value),
                    }))
                  }
                  className={SELECT_CLASS}
                >
                  <option value={UNMAPPED}>— not imported —</option>
                  {table.headers.map((header, index) => (
                    <option key={`${header}-${index}`} value={index}>
                      {header}
                    </option>
                  ))}
                </select>
                <span className="mt-1 block truncate font-mono text-[11px] text-muted/70">
                  {column === UNMAPPED ? field.placeholder : (sample ?? 'no values in this column')}
                </span>
              </label>
            )
          })}
        </div>

        <div className="border-t border-line/60 pt-4">
          <label className="block max-w-sm">
            <span className="text-xs text-muted">Rows with a blank or unknown category</span>
            <select
              value={fallbackCategoryId}
              onChange={(event) => setFallbackCategoryId(event.target.value)}
              className={SELECT_CLASS}
            >
              <option value="">Leave them out (reported as errors)</option>
              {categoriesForFallback.map((category) => (
                <option key={category.id} value={category.id}>
                  Import as {category.name}
                </option>
              ))}
            </select>
          </label>
        </div>
      </section>

      {plan && plan.blockers.length > 0 && (
        <div className="rounded-xl border border-warn/40 bg-warn/10 p-4 text-sm">
          <p className="font-semibold text-warn">Mapping not finished</p>
          <ul className="mt-1 space-y-0.5 text-xs text-muted">
            {plan.blockers.map((blocker) => (
              <li key={blocker}>{blocker}</li>
            ))}
          </ul>
        </div>
      )}

      {referencesLoading && (
        <p className="text-xs text-muted">Loading categories, rooms and staff…</p>
      )}

      {plan && plan.blockers.length === 0 && !referencesLoading && (
        <>
          <div className="flex flex-wrap items-center gap-x-4 gap-y-2 rounded-xl border border-line bg-panel px-4 py-3 text-xs">
            <span className="font-semibold text-ink">{plan.ready} ready to import</span>
            {plan.rowsWithErrors > 0 && (
              <span className="text-bad">{plan.rowsWithErrors} with problems</span>
            )}
            {plan.rowsWithWarnings > 0 && (
              <span className="text-warn">{plan.rowsWithWarnings} with warnings</span>
            )}
            <button
              type="button"
              onClick={commit}
              disabled={plan.ready === 0 || committing}
              className="ml-auto rounded-lg border border-accent/50 bg-accent/15 px-3 py-1.5 text-xs font-semibold text-accent transition-colors hover:bg-accent/25 disabled:opacity-40"
            >
              {committing ? 'Importing…' : `Import ${plan.ready} ${plan.ready === 1 ? 'device' : 'devices'}`}
            </button>
          </div>

          {commitError && (
            <p className="rounded-lg border border-bad/40 bg-bad/10 px-3 py-2 text-xs text-bad">
              Nothing was imported: {commitError}
            </p>
          )}

          <div className="overflow-x-auto rounded-xl border border-line bg-panel">
            <table className="w-full border-collapse text-sm">
              <thead className="border-b border-line bg-panel-2">
                <tr>
                  {['Row', 'Asset tag', 'Serial', 'Brand / model', 'Category', 'Status', 'Dry run'].map(
                    (label) => (
                      <th
                        key={label}
                        scope="col"
                        className="px-3 py-2 text-left text-[11px] font-bold tracking-wider text-muted uppercase whitespace-nowrap"
                      >
                        {label}
                      </th>
                    ),
                  )}
                </tr>
              </thead>
              <tbody>
                {previewRows.map((row) => {
                  const clean = row.errors.length === 0 && row.warnings.length === 0
                  return (
                    <tr key={row.rowNumber} className="border-b border-line/70 align-top last:border-b-0">
                      <td className="px-3 py-2 font-mono text-[11px] text-muted">{row.rowNumber}</td>
                      <td className="px-3 py-2 font-mono text-[12.5px] whitespace-nowrap">
                        {row.preview.assetTag || <span className="text-warn italic">none</span>}
                      </td>
                      <td className="px-3 py-2 font-mono text-[12.5px] whitespace-nowrap text-muted">
                        {row.preview.serial || '—'}
                      </td>
                      <td className="px-3 py-2 whitespace-nowrap">
                        {row.preview.brand} {row.preview.model}
                      </td>
                      <td className="px-3 py-2 whitespace-nowrap text-muted">{row.preview.category || '—'}</td>
                      <td className="px-3 py-2 whitespace-nowrap text-muted">{row.preview.status}</td>
                      <td className="max-w-md px-3 py-2">
                        {clean && <span className="text-xs text-accent-2">ready</span>}
                        {row.errors.map((error) => (
                          <div key={error} className="text-[11px] leading-relaxed text-bad">
                            {error}
                          </div>
                        ))}
                        {row.warnings.map((warning) => (
                          <div key={warning} className="text-[11px] leading-relaxed text-warn">
                            {warning}
                          </div>
                        ))}
                      </td>
                    </tr>
                  )
                })}
              </tbody>
            </table>
            {plan.rows.length === 0 && (
              <p className="px-4 py-8 text-center text-sm text-muted">No rows to show.</p>
            )}
            {plan.rows.length > PREVIEW_LIMIT && (
              <p className="border-t border-line/70 px-3 py-2 text-[11px] text-muted">
                Showing the first {PREVIEW_LIMIT} of {plan.rows.length} rows. Every row is checked, not
                just these.
              </p>
            )}
          </div>
        </>
      )}
    </div>
  )
}
